import type { AssetCandidate, AssetRecord, AssetSelection, Scene, Shot } from "@cineforge/schemas";
import { formatDuration, humanize } from "@/lib/format";
import { aiDisclosureBadge, assetIndex, generatedBy, type DisclosureBadge } from "@/lib/generation";
import { attributionText, candidateIndex } from "@/lib/review";
import { shotProgress, type StageProgress } from "@/lib/shotProgress";
import { Badge, Card, EmptyState, cx } from "../../ui";
import { AssetThumb } from "./AssetThumb";
import { RightsBadge } from "./badges";

function disclosureBadge(shot: Shot): DisclosureBadge | null {
  const ai = aiDisclosureBadge(shot);
  if (ai) return ai;
  const d = shot.disclosure;
  if (d?.label_text) return { text: d.label_text, title: "AI disclosure shown on screen" };
  if (d?.reconstruction) return { text: "Reconstruction", title: "AI disclosure shown on screen" };
  return null;
}

const DOT: Record<Exclude<StageProgress, "skipped">, string> = {
  complete: "bg-emerald-400",
  active: "animate-[status-blink_1.1s_ease-in-out_infinite] bg-sky-400",
  pending: "bg-zinc-600 ring-1 ring-inset ring-zinc-500/50",
  failed: "bg-rose-400",
};

function StatusDot({
  state,
  label,
  title,
}: {
  state: StageProgress;
  label?: string;
  title?: string;
}) {
  if (state === "skipped") return null;
  return (
    <span
      data-testid="storyboard-status-dot"
      data-state={state}
      title={title ?? label}
      aria-label={title ?? label}
      className="inline-flex items-center gap-1"
    >
      <span aria-hidden="true" className={cx("inline-block h-2 w-2 shrink-0 rounded-full", DOT[state])} />
      {label && <span className="text-[11px] text-zinc-500">{label}</span>}
    </span>
  );
}

function ShotStatus({ shot }: { shot: Shot }) {
  const progress = shotProgress(shot);
  return (
    <div
      data-testid="storyboard-shot-status"
      data-overall={progress.overall}
      className="mt-2 flex flex-wrap items-center gap-x-3 gap-y-1"
      aria-label={`Shot status: ${progress.label}`}
    >
      <StatusDot
        state={progress.overall}
        label={progress.label}
        title={`Shot ${progress.label.toLowerCase()}`}
      />
      {progress.stages.length > 0 && (
        <span className="flex flex-wrap items-center gap-2 border-l border-white/[0.06] pl-3">
          {progress.stages
            .filter((s) => s.state !== "skipped")
            .map((stage) => (
              <StatusDot
                key={stage.id}
                state={stage.state}
                label={stage.label}
                title={`${stage.label}: ${stage.state}`}
              />
            ))}
        </span>
      )}
    </div>
  );
}

function BoundAsset({ candidate, blockedReason }: { candidate: AssetCandidate; blockedReason?: string }) {
  return (
    <figure data-testid="storyboard-asset" data-asset={candidate.candidate_id} className="w-36">
      <AssetThumb candidate={candidate} className="aspect-[9/16] w-36" />
      <figcaption className="mt-1.5 space-y-1">
        <RightsBadge status={candidate.rights_status} />
        <p className="text-[11px] leading-snug text-zinc-500" data-testid="asset-attribution">
          {attributionText(candidate)}
        </p>
        {blockedReason && <p className="text-[11px] text-rose-300">{blockedReason}</p>}
      </figcaption>
    </figure>
  );
}

function ShotCard({
  shot,
  candidates,
  blocked,
  assets,
}: {
  shot: Shot;
  candidates: Map<string, AssetCandidate>;
  blocked: Record<string, string>;
  assets: ReadonlyMap<string, AssetRecord>;
}) {
  const bound = (shot.assets ?? [])
    .map((ref) => candidates.get(ref.asset_id))
    .filter((c): c is AssetCandidate => c !== undefined);
  const disclosure = disclosureBadge(shot);
  const generator = generatedBy(shot, assets);
  return (
    <li data-testid="storyboard-shot" className="rounded-lg border border-white/[0.05] bg-white/[0.015] p-3">
      <div className="flex flex-wrap items-center gap-1.5 text-xs">
        <span className="font-mono text-zinc-600">#{shot.order}</span>
        <span className="text-zinc-200">{humanize(shot.visual.shot_type)}</span>
        <span className="text-zinc-500">· {humanize(shot.visual.camera_motion)}</span>
        <span className="text-zinc-500">· {formatDuration(shot.duration_sec)}</span>
        <Badge>{humanize(shot.provider_plan?.strategy ?? "generative")}</Badge>
        {disclosure && (
          <Badge tone="violet" title={disclosure.title}>
            {disclosure.text}
          </Badge>
        )}
        {generator && (
          <span data-testid="shot-generated-by" title="Generated by" className="font-mono text-[11px] text-sky-300/80">
            {generator}
          </span>
        )}
      </div>
      {shot.description && <p className="mt-1 text-xs text-zinc-400">{shot.description}</p>}
      <ShotStatus shot={shot} />
      {bound.length > 0 && (
        <div className="mt-2 flex flex-wrap gap-3">
          {bound.map((c) => (
            <BoundAsset key={c.candidate_id} candidate={c} blockedReason={blocked[c.candidate_id]} />
          ))}
        </div>
      )}
    </li>
  );
}

function Legend() {
  return (
    <ul
      data-testid="storyboard-legend"
      className="flex flex-wrap gap-x-4 gap-y-1 text-[11px] text-zinc-500"
      aria-label="Storyboard status legend"
    >
      <li className="inline-flex items-center gap-1.5">
        <span aria-hidden="true" className="h-2 w-2 rounded-full bg-emerald-400" /> Complete
      </li>
      <li className="inline-flex items-center gap-1.5">
        <span
          aria-hidden="true"
          className="h-2 w-2 animate-[status-blink_1.1s_ease-in-out_infinite] rounded-full bg-sky-400"
        />{" "}
        In progress
      </li>
      <li className="inline-flex items-center gap-1.5">
        <span aria-hidden="true" className="h-2 w-2 rounded-full bg-zinc-600 ring-1 ring-inset ring-zinc-500/50" />{" "}
        Not started
      </li>
      <li className="inline-flex items-center gap-1.5">
        <span aria-hidden="true" className="h-2 w-2 rounded-full bg-rose-400" /> Failed
      </li>
    </ul>
  );
}

export function StoryboardPanel({
  scenes,
  media,
  assets,
}: {
  scenes: readonly Scene[];
  media?: AssetSelection | null;
  assets?: readonly AssetRecord[];
}) {
  const sorted = [...scenes].sort((a, b) => a.order - b.order);
  const candidates = candidateIndex(media);
  const records = assetIndex(assets);
  const blocked = media?.blocked ?? {};
  return (
    <Card
      id="storyboard"
      title="Storyboard"
      description="Scenes, shots and progress. Blinking = work in progress; steady dots = complete or not started."
      actions={<Legend />}
    >
      {sorted.length === 0 ? (
        <EmptyState title="No storyboard yet">The Scene Director (A6) builds it during storyboarding.</EmptyState>
      ) : (
        <div className="grid gap-3 lg:grid-cols-2">
          {sorted.map((scene) => (
            <article
              key={scene.id}
              data-testid="storyboard-scene"
              aria-label={`Storyboard scene ${scene.order}: ${scene.title || "Untitled"}`}
              className="rounded-xl border border-white/[0.06] bg-white/[0.015] p-4"
            >
              <header className="flex items-start gap-3">
                <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-gold-500/10 text-sm font-semibold text-gold-300 ring-1 ring-gold-500/20">
                  {scene.order}
                </span>
                <div className="min-w-0">
                  <h3 className="text-sm font-semibold text-zinc-100">{scene.title || `Scene ${scene.order}`}</h3>
                  <p className="text-xs text-zinc-500">
                    {scene.story_beat ? humanize(scene.story_beat) : "No beat"} · {formatDuration(scene.duration_sec)}
                  </p>
                </div>
              </header>
              {scene.narration && <p className="mt-2 text-sm italic text-zinc-400">&ldquo;{scene.narration}&rdquo;</p>}
              <ul className="mt-3 space-y-2">
                {scene.shots.map((shot) => (
                  <ShotCard key={shot.id} shot={shot} candidates={candidates} blocked={blocked} assets={records} />
                ))}
              </ul>
            </article>
          ))}
        </div>
      )}
    </Card>
  );
}
