"""Generate supabase/seed.sql from packages/configurations (themes, price catalogs).

Output is idempotent SQL: re-applying it upserts configuration rows and never
resets credit balances that have already been spent down.

Usage:
    uv run python scripts/generate_seed.py           # write supabase/seed.sql
    uv run python scripts/generate_seed.py --check   # fail if seed.sql is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from decimal import Decimal
from pathlib import Path

from cineforge.configuration import load_themes
from cineforge.contracts.common import DEMO_TENANT_ID
from cineforge.cost.catalog import YamlPriceCatalog
from cineforge.cost.credits import SIMULATED_CREDIT_BALANCES

ROOT = Path(__file__).resolve().parents[1]
CONFIG_DIR = ROOT / "packages" / "configurations"
OUTPUT = ROOT / "supabase" / "seed.sql"
DEMO_TENANT_NAME = "CineForge Demo Studio"


def q(value: object) -> str:
    """SQL literal for str/int/Decimal/bool/None."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | Decimal):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _values(rows: list[str]) -> str:
    return ",\n".join(f"    {r}" for r in rows)


def render(config_dir: Path = CONFIG_DIR) -> str:
    out: list[str] = [
        "-- GENERATED by scripts/generate_seed.py from packages/configurations. DO NOT EDIT.",
        "-- Regenerate: uv run python scripts/generate_seed.py (CI: --check). Owner: Workstream D.",
        "-- Idempotent: configuration rows are upserted; spent credit balances are never reset.",
        "",
        "-- ------------------------------------------------------------- tenants",
        "insert into public.tenants (id, name) values",
        _values([f"({q(DEMO_TENANT_ID)}, {q(DEMO_TENANT_NAME)})"]),
        "on conflict (id) do nothing;",
        "",
    ]

    themes = sorted(load_themes(config_dir).values(), key=lambda t: (t.id, t.version))
    theme_rows = [
        f"({q(t.id)}, {t.version}, {q(t.name)}, "
        f"{q(json.dumps(t.model_dump(mode='json'), ensure_ascii=False, sort_keys=True))}::jsonb)"
        for t in themes
    ]
    out += [
        "-- ------------------------------------------------------------- theme profiles",
        "insert into public.theme_profiles (id, version, name, config) values",
        _values(theme_rows),
        "on conflict (id, version) do update set name = excluded.name, config = excluded.config;",
        "",
    ]

    price_rows: list[str] = []
    for path in sorted((config_dir / "pricing").glob("*.yaml")):
        catalog = YamlPriceCatalog.from_file(path)
        for e in catalog.entries():
            price_rows.append(
                f"({q(e.version)}, {q(e.provider)}, {q(e.model)}, {q(e.capability.value)}, "
                f"{q(e.unit.value)}, {q(e.unit_price)}, {q(e.currency)}, "
                f"{q(e.credits_per_unit)}, {q(e.effective_from.isoformat())}, "
                f"{q(e.effective_to.isoformat() if e.effective_to else None)}, "
                f"{q(catalog.simulated)}, {q(e.notes)})"
            )
    out += [
        "-- ------------------------------------------------------------- price catalog",
        "insert into public.price_catalog (version, provider, model, capability, unit, unit_price,",
        "    currency, credits_per_unit, effective_from, effective_to, simulated, notes) values",
        _values(price_rows),
        "on conflict (version, provider, model, unit) do update set",
        "    capability = excluded.capability, unit_price = excluded.unit_price,",
        "    currency = excluded.currency, credits_per_unit = excluded.credits_per_unit,",
        "    effective_from = excluded.effective_from, effective_to = excluded.effective_to,",
        "    simulated = excluded.simulated, notes = excluded.notes;",
        "",
    ]

    credit_rows = [
        f"({q(DEMO_TENANT_ID)}, {q(provider)}, {q(balance)}, 'credit', true)"
        for provider, balance in sorted(SIMULATED_CREDIT_BALANCES.items())
    ]
    out += [
        "-- ------------------------------------------------------------- simulated credits",
        "insert into public.credit_balances (tenant_id, provider, balance, unit, is_estimated)",
        "values",
        _values(credit_rows),
        "on conflict (tenant_id, provider) do nothing;",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if seed.sql is out of date")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != content:
            print(
                f"{OUTPUT.relative_to(ROOT)} is stale; run: uv run python scripts/generate_seed.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
