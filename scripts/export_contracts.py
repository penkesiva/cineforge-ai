"""Export the frozen Pydantic contracts as one JSON Schema document.

Output: packages/schemas/json/contracts.schema.json (committed). TypeScript types
are then generated from it by `npm run generate --workspace @cineforge/schemas`.

Usage:
    uv run python scripts/export_contracts.py           # write
    uv run python scripts/export_contracts.py --check   # fail if out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from cineforge.contracts import agents, api, cost, manifest, media, providers, review, theme
from cineforge.contracts import workflow as wf
from cineforge.testing import sample_manifest
from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "packages" / "schemas" / "json" / "contracts.schema.json"
FIXTURE = ROOT / "packages" / "schemas" / "fixtures" / "sample-manifest.json"

# Models the dashboard reads (serialization mode: what the API returns).
RESPONSE_MODELS: list[type[BaseModel]] = [
    api.HealthResponse,
    api.ProductionSummary,
    api.ProductionDetail,
    api.ActionResponse,
    api.ErrorResponse,
    agents.AgentDefinition,
    agents.AgentRun,
    manifest.ProductionManifest,
    cost.CostSummary,
    cost.CostOverview,
    cost.CostEstimate,
    cost.PriceCatalogEntry,
    cost.LedgerEvent,
    cost.CreditBalance,
    media.AssetRecord,
    review.ReviewReport,
    theme.ThemeSummary,
    theme.ThemeProfile,
    theme.ProductionModePolicy,
    providers.ProviderInfo,
    providers.ProviderCatalogEntry,
    api.ProvidersOverview,
    api.ProviderTestResult,
    api.GenerationPack,
    api.ExternalGenerationResponse,
    api.StageQuote,
    api.OAuthStartResponse,
    api.ConnectorStatus,
    api.CharacterSummary,
    wf.ProductionEvent,
]

# Models the dashboard sends (validation mode).
REQUEST_MODELS: list[type[BaseModel]] = [
    api.CreateProductionRequest,
    api.ApproveProductionRequest,
    api.ReviewClaimsRequest,
    api.UpdateProviderRequest,
    api.SetProviderKeyRequest,
    api.CreateThemeVersionRequest,
    api.ExternalGenerationRequest,
    api.ExternalGenerationComplete,
    api.ExternalGenerationRelease,
    api.RenderRequest,
    api.RegenerateShotRequest,
]


def _ordered(states: frozenset[wf.ProductionState]) -> list[str]:
    return [s.value for s in wf.ProductionState if s in states]


def build_schema() -> dict:
    _, response_schema = models_json_schema(
        [(m, "serialization") for m in RESPONSE_MODELS], ref_template="#/$defs/{model}"
    )
    _, request_schema = models_json_schema(
        [(m, "validation") for m in REQUEST_MODELS], ref_template="#/$defs/{model}"
    )
    defs: dict = dict(response_schema.get("$defs", {}))
    for name, definition in request_schema.get("$defs", {}).items():
        if name in defs and defs[name] != definition:
            raise SystemExit(f"Schema name collision with differing definitions: {name}")
        defs[name] = definition

    exported = [m.__name__ for m in RESPONSE_MODELS + REQUEST_MODELS]
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "CineForgeContracts",
        "description": "GENERATED by scripts/export_contracts.py - do not edit.",
        "type": "object",
        "properties": {name: {"$ref": f"#/$defs/{name}"} for name in exported},
        "$defs": dict(sorted(defs.items())),
        "x-enums": {
            "ProductionStateOrder": [s.value for s in wf.ProductionState],
            "HappyPath": [s.value for s in wf.HAPPY_PATH],
            "WorkingStates": _ordered(wf.WORKING_STATES),
            "TerminalStates": _ordered(wf.TERMINAL_STATES),
            "ExceptionStates": _ordered(wf.EXCEPTION_STATES),
            "AllowedTransitions": {
                s.value: _ordered(wf.ALLOWED_TRANSITIONS[s]) for s in wf.ProductionState
            },
        },
        "x-agent-definitions": [d.model_dump(mode="json") for d in agents.AGENT_DEFINITIONS],
    }


def build_outputs() -> dict[Path, str]:
    return {
        OUTPUT: json.dumps(build_schema(), indent=2) + "\n",
        FIXTURE: sample_manifest().model_dump_json(indent=2) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = build_outputs()
    if args.check:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date. Run `make contracts`.")
        if not stale:
            print("contracts schema is up to date")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
